REG = []  # (番号, 区分, タイトル, 分, 出典, ノート文字数)
BLOCK = {"cur": "main"}


def reg(kind, title, minutes, src, notes, src_optional=False):
    assert len(title) <= 25, f"title too long: {title}"
    if kind not in ("section", "title"):
        assert notes and (len(notes) > 60 or BLOCK["cur"] == "補足"), f"notes missing: {title}"
        if not src_optional:
            assert src.startswith(LABELS), f"source label: {title}: {src}"
    assert len(src) <= 175, f"source too long ({len(src)}): {title}"
    REG.append((len(REG) + 1, BLOCK["cur"], kind, title, minutes, src, len(notes or "")))


def title_slide(title, sub, notes):
    d.title_slide(title, sub, notes)
    reg("title", title, 0.5, "", notes)


def section(title, sub, notes, minutes=0.0):
    d.section(title, sub, notes)
    reg("section", title, minutes, "", notes)


def bullets(title, items, minutes, src, notes, **kw):
    d.bullets(title, items, notes=notes, source=src, **kw)
    reg("bullets", title, minutes, src, notes, src_optional=kw.get("src_optional", False) if False else not src)


def _lead(s, text, h):
    d.textbox(s, text, LEFT, BODY_TOP, FULL_W, h, size=24)


def lead_img(title, lead, path, minutes, src, notes, caption="", lead_h=900000, eq=None, eq_size=32):
    """文字（リード）が上，図が下．"""
    s = d._new(L_TITLEONLY)
    s.shapes.title.text = title
    _tag_runs(s.shapes.title.text_frame._txBody)
    _lead(s, lead, lead_h)
    top = BODY_TOP + lead_h
    if eq:
        top += d.equation(s, eq, LEFT, top, FULL_W, size=eq_size) + 60000
    cap_h = 420000 if caption else 0
    bottom = SRC_TOP - 40000
    d._place_image(s, path, LEFT, top, FULL_W, bottom - top - cap_h)
    if caption:
        d.textbox(s, caption, LEFT, bottom - cap_h, FULL_W, cap_h, size=16, align=PP_ALIGN.CENTER)
    d.source(s, src)
    d._notes(s, notes)
    reg("figure", title, minutes, src, notes)


def lead_table(title, lead, rows, minutes, src, notes, col_widths=None, size=18, highlight=None, lead_h=800000, row_h=470000, eq=None, eq_size=32):
    s = d._new(L_TITLEONLY)
    s.shapes.title.text = title
    _tag_runs(s.shapes.title.text_frame._txBody)
    top = BODY_TOP
    if lead:
        _lead(s, lead, lead_h)
        top += lead_h
    if eq:
        top += d.equation(s, eq, LEFT, top, FULL_W, size=eq_size) + 80000
    nr, nc = len(rows), len(rows[0])
    from pptx.util import Pt
    gf = s.shapes.add_table(nr, nc, Emu(LEFT), Emu(top), Emu(FULL_W), Emu(row_h * nr))
    tbl = gf.table
    if col_widths:
        tot = sum(col_widths)
        for i, w in enumerate(col_widths):
            tbl.columns[i].width = Emu(int(FULL_W * w / tot))
    for i, row in enumerate(rows):
        tbl.rows[i].height = Emu(row_h)
        for j, v in enumerate(row):
            c = tbl.cell(i, j)
            c.text = str(v)
            for p in c.text_frame.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(size)
                    r.font.bold = i == 0 or bool(highlight and (i, j) in highlight)
            _tag_runs(c.text_frame._txBody)
    d.source(s, src)
    d._notes(s, notes)
    reg("table", title, minutes, src, notes)



def formula_slide(title, eqs, conds, lines, minutes, src, notes):
    """主役の式（大きく）→ 条件の式（ラベル付き）→ 記号の説明（24pt）の順に置く．"""
    s = d._new(L_TITLEONLY)
    s.shapes.title.text = title
    _tag_runs(s.shapes.title.text_frame._txBody)
    y = BODY_TOP + 60000
    for latex in eqs:
        y += d.equation(s, latex, LEFT, y, FULL_W, size=46) + 60000
    y += 120000
    for label, latex in conds:
        d.textbox(s, label, LEFT, y, 3900000, 560000, size=24)
        h = d.equation(s, latex, LEFT + 3900000, y, FULL_W - 3900000, size=34, align="left")
        y += max(h, 620000) + 30000
    y += 120000
    d.textbox(s, "\n".join(lines), LEFT, y, FULL_W, SRC_TOP - y - 80000, size=24)
    d.source(s, src)
    d._notes(s, notes)
    reg("formula", title, minutes, src, notes)


